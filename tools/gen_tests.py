MOD=10**9+7
def dice(n,k,t):
    dp=[0]*(t+1); dp[0]=1
    for _ in range(n):
        nd=[0]*(t+1)
        for s in range(1,t+1):
            nd[s]=sum(dp[s-f] for f in range(1,k+1) if s-f>=0)%MOD
        dp=nd
    return dp[t]
def book(orders):
    bids=[];asks=[];vol=0;seq=0
    for side,p,q in orders:
        seq+=1
        if side=='B':
            while q and asks and asks[0][0]<=p:
                ap,s,aq=asks[0]; x=min(q,aq); vol+=x; q-=x
                if aq==x: heapq.heappop(asks)
                else: asks[0]=(ap,s,aq-x)
            if q: heapq.heappush(bids,(-p,seq,q))
        else:
            while q and bids and -bids[0][0]>=p:
                bp,s,bq=bids[0]; x=min(q,bq); vol+=x; q-=x
                if bq==x: heapq.heappop(bids)
                else: bids[0]=(bp,s,bq-x)
            if q: heapq.heappush(asks,(p,seq,q))
    bb=-bids[0][0] if bids else -1; ba=asks[0][0] if asks else -1
    return f"{vol}\n{bb} {ba}"
def cards(R,B):
    prev=[0.0]*(B+1)  # r=0: value 0
    for r in range(1,R+1):
        cur=[0.0]*(B+1); cur[0]=float(r)
        for b in range(1,B+1):
            cur[b]=max(0.0,(r*(1+prev[b])+b*(-1+cur[b-1]))/(r+b))
        prev=cur
    return f"{prev[B]:.6f}"
